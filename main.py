#!/usr/bin/env python3
"""The Meeting That Should Have Been One Line.

Prints one line: the entire meeting, distilled.
"""

LINE = (
    "Forty-seven people, one hour, and the meeting's only decision "
    "was to schedule another meeting — the email already knew."
)

def main() -> None:
    print(LINE)


if __name__ == "__main__":
    main()
